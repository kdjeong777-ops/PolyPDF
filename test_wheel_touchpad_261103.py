def replay(rec):
    flips = []
    m.view.pageStep.connect(flips.append)
    t = time.perf_counter()
    for tok in rec.strip(",").split(","):
        dt, dy = tok.split(":")
        t += int(dt) / 1000.0
        while time.perf_counter() < t:
            app.processEvents()
            time.sleep(0.001)
        send(int(dy))
    pump(400)
    m.view.pageStep.disconnect(flips.append)
    return flips


